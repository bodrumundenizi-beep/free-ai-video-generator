GROUP_NAMES = {"speed": "Speed", "gaming": "Gaming", "battery": "Battery", "storage": "Storage",
               "privacy": "Privacy", "eyes": "Eyes", "looks": "Looks", "sound": "Sound",
               "handy": "Handy"}


def groups() -> list:
    """[(group name, [tip text, ...])] in GROUP_NAMES order, for the picker."""
    by_kind = {}
    for text, place_id in TIPS:
        by_kind.setdefault(hooks.kind_of(winmap.BY_ID[place_id]), []).append(text)
    return [(GROUP_NAMES[k], by_kind[k]) for k in GROUP_NAMES if k in by_kind]
